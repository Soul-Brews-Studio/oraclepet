#!/usr/bin/env bash
# Editor support: write .clangd so clangd (VS Code, Zed, Claude Code's LSP) understands the
# firmware sources. Run after `idf.py build` (it reads build/compile_commands.json).
#
# The compile database holds xtensa-gcc flags clang rejects, and gcc finds its libc headers
# (picolibc) inside the toolchain, not through -I. So: drop the gcc-only flags, and add the
# include dirs gcc itself reports. The paths are per machine, which is why .clangd is
# generated and gitignored rather than committed.
set -euo pipefail
# an optional argument: another IDF project to set up (lab/discord-voice-esp32), default this one
cd "${1:-$(dirname "$0")/..}"
DB=build/compile_commands.json
[ -f "$DB" ] || { echo "no $DB: run idf.py build first" >&2; exit 1; }
read -r CC SPECS < <(python3 -c "
import json,shlex
e=json.load(open('$DB'))[0]; a=e.get('arguments') or shlex.split(e['command'])
print(a[0], ' '.join(x for x in a if x.startswith('-specs=')))")
# IDF 6 picks the libc in sdkconfig; the compile database does not carry -specs for it
grep -q '^CONFIG_LIBC_PICOLIBC=y' sdkconfig 2>/dev/null && SPECS="$SPECS -specs=picolibc.specs"
# the libc headers gcc really uses (IDF 6: -specs=picolibc.specs); skip gcc's own builtin
# headers (stdarg.h, stddef.h...): clang brings its own and the two sets clash
INC=$("$CC" $SPECS -E -v -x c /dev/null 2>&1 | sed -n '/#include <...> search starts here:/,/End of search list./p' | sed '1d;$d' | sed 's/^ *//' | rg -v '/lib/gcc/')
{
  echo "# generated by tools/clangd-setup.sh for $CC"
  echo "CompileFlags:"
  echo "  CompilationDatabase: build"
  echo "  Remove: [-mlongcalls, -mdisable-hardware-atomics, -fno-shrink-wrap, -fstrict-volatile-bitfields,"
  echo "           -fno-tree-switch-conversion, -fzero-init-padding-bits=*, -fno-malloc-dce, -fno-jump-tables,"
  echo "           -fmacro-prefix-map=*, -fdiagnostics-color=*, -specs=*]"
  echo "  Add:"
  echo "    - -Wno-unknown-warning-option"
  echo "    - -D__XTENSA__"
  while read -r d; do [ -n "$d" ] && echo "    - -isystem$(cd "$d" && pwd)"; done <<< "$INC"
  echo "Diagnostics:"
  echo "  # IRAM_ATTR names an ELF section; host clang checks it against Mach-O rules"
  echo "  Suppress: [attribute_section_invalid_for_target]"
  echo "---"
  echo "# lcd28-only sources: build/ is the JC3248 build, so give them the lcd28 board switch."
  echo "If:"
  echo "  PathMatch: main/display_ili9341\\.c"
  echo "CompileFlags:"
  echo "  Add: [-DPET_BOARD_LCD28=1]"
} > .clangd
echo "wrote .clangd ($(echo "$INC" | wc -l | tr -d ' ') toolchain include dirs)"
