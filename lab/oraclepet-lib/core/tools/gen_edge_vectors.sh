#!/usr/bin/env bash
# Regenerate tests/edge_vectors.json and tests/hb_cases.h from the Swift PetProtocol (the
# reference): the OraclePetEdgeVectors and OraclePetHeartbeatCases targets in lab/desk-pet-mac.
# Needs Swift (macOS); the outputs are checked in, so `make test` itself never needs Swift.
set -euo pipefail
cd "$(dirname "$0")/.."
PKG=../../desk-pet-mac
swift build -q --package-path "$PKG" --product OraclePetEdgeVectors
swift build -q --package-path "$PKG" --product OraclePetHeartbeatCases
BIN=$(swift build --package-path "$PKG" --show-bin-path)
"$BIN/OraclePetEdgeVectors" > tests/edge_vectors.json
(echo '/* generated by OraclePetHeartbeatCases (lab/desk-pet-mac) from Heartbeat.swift: do not edit */'; "$BIN/OraclePetHeartbeatCases") > tests/hb_cases.h
echo "tests/edge_vectors.json: $(wc -c < tests/edge_vectors.json | tr -d ' ') bytes, tests/hb_cases.h: $(wc -l < tests/hb_cases.h | tr -d ' ') lines"
