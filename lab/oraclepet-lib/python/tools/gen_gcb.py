#!/usr/bin/env python3
"""Write oraclepet/_gcb.py: the grapheme-break class table Heartbeat clipping needs.

Swift clips the heartbeat's msg and who by Character (UAX #29 grapheme clusters), so the
bytes only match when Python breaks text the same way. The table is not derived here: it is
read out of ../core/oraclepet.c, which core/tools/gen_gcb_table.sh fills from Swift's own
String breaking. One table, read off the reference, shared by C and Python.

Run after core/tools/gen_gcb_table.sh rewrites the C table:  python3 tools/gen_gcb.py
"""
import re
from pathlib import Path

here = Path(__file__).resolve().parent.parent
src = (here.parent / "core" / "oraclepet.c").read_text()
body = re.search(r"static const uint32_t gcb_table\[\d+\] = \{(.*?)\};", src, re.DOTALL).group(1)
entries = [int(x, 16) for x in re.findall(r"0x([0-9a-f]+)u", body)]
starts = [e >> 4 for e in entries]
classes = [e & 15 for e in entries]

out = [
    '"""Grapheme-break classes above ASCII, read off Swift by core/tools/gen_gcb_table.sh.',
    "",
    "Generated by tools/gen_gcb.py from core/oraclepet.c's gcb_table; do not edit. STARTS[i]",
    "begins a run of code points of class CLASSES[i] that lasts up to STARTS[i + 1]. Classes:",
    "0 other, 1 control, 2 extend (InCB extend), 3 extend only, 4 InCB linker, 5 spacing mark,",
    '6 prepend, 7 extended pictographic, 8 InCB consonant."""',
    "",
    "STARTS = (",
]
for i in range(0, len(starts), 10):
    out.append("    " + " ".join(f"0x{s:05x}," for s in starts[i:i + 10]))
out.append(")")
out.append("CLASSES = bytes((")
for i in range(0, len(classes), 30):
    out.append("    " + " ".join(f"{c}," for c in classes[i:i + 30]))
out.append("))")
(here / "oraclepet" / "_gcb.py").write_text("\n".join(out) + "\n")
print(f"oraclepet/_gcb.py: {len(entries)} entries")
